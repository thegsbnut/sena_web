// Builds the redesign preview: copies public/ into dist-next/, overlays next/, then writes
// .next-build/assets.mjs (every file of dist-next/ as a module) for worker-next.js to serve.
// Production (wrangler.jsonc → public/) is untouched; only wrangler.next.jsonc uses this output.
import {
  cpSync,
  rmSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
  statSync,
} from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const textTypes = /\.(html|css|js|json|webmanifest|svg|txt)$/;

function walk(dir) {
  return readdirSync(dir).flatMap(name => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

export function assetModule(dir) {
  const files = {};
  for (const path of walk(dir).sort()) {
    const name = relative(dir, path).split(sep).join('/');
    files[name] = textTypes.test(name)
      ? { text: readFileSync(path, 'utf8') }
      : { base64: readFileSync(path).toString('base64') };
  }
  return (
    '// Generated by scripts/build-next.mjs. Do not edit.\nexport const files = ' +
    JSON.stringify(files) +
    ';\n'
  );
}

export function buildNext(out = root + 'dist-next', moduleOut = root + '.next-build/assets.mjs') {
  // Empty the folder instead of deleting it, so a running `wrangler dev` keeps watching it.
  mkdirSync(out, { recursive: true });
  for (const name of readdirSync(out)) rmSync(join(out, name), { recursive: true, force: true });
  cpSync(root + 'public', out, { recursive: true });
  cpSync(root + 'next', out, { recursive: true });
  if (moduleOut) {
    mkdirSync(join(moduleOut, '..'), { recursive: true });
    writeFileSync(moduleOut, assetModule(out));
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) console.log('built', buildNext());
